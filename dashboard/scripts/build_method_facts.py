"""Write dashboard/src/data/methodFacts.json: the few numbers on the Scenarios
and method and Literature tabs that are not in surprise2028.json.

Every value is read from a committed file; nothing is typed in.
  - baseline GDP growth 2027-30: analysis/rerun/output/<closure>/baseline_p1.json,
    re-trended exactly as uk_growth_with_ai.report.growth_path does
    (detrended Y x e^(g_y t) x population);
  - employer and employee NICs rates: analysis/nics/nics_<year>.json
    (PolicyEngine-UK, measured by analysis/nics/measure_nics.py);
  - OG-UK's flat employer payroll rate (tau_payroll) from the same file.

    python dashboard/scripts/build_method_facts.py
"""
from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / "dashboard" / "src" / "data" / "methodFacts.json"


def baseline_growth(closure: str) -> dict:
    src = ROOT / "analysis" / "rerun" / "output" / closure / "baseline_p1.json"
    d = json.loads(src.read_text())
    years, y, g_n, g_y = d["years"], d["series"]["Y"], d["g_n_used"], d["g_y_annual_used"]
    i0, i1 = years.index(2026), years.index(2030)
    growth = [(y[i] / y[i - 1] * math.exp(g_y) * (1 + g_n[i - 1]) - 1) * 100 for i in range(i0 + 1, i1 + 1)]
    return {
        "years": years[i0 + 1:i1 + 1],
        "growth_pct": growth,
        "mean_pct": sum(growth) / len(growth),
        "source": str(src.relative_to(ROOT)),
    }


def nics(year: int) -> dict:
    src = ROOT / "analysis" / "nics" / f"nics_{year}.json"
    d = json.loads(src.read_text())
    return {
        "year": d["year"],
        "employer_avg_of_labour_cost": d["avg_employer_rate_on_total_labour_cost"],
        "employer_avg_of_employment_income": d["avg_employer_rate_on_employment_income"],
        "employer_marginal": d["marginal_employer_rate_earnings_weighted"],
        "employee_avg_of_employment_income": d["avg_employee_rate_on_employment_income"],
        "oguk_tau_payroll": d["oguk_tau_payroll"],
        "source": str(src.relative_to(ROOT)),
    }


def main():
    out = {
        "_note": "Generated by dashboard/scripts/build_method_facts.py; do not edit by hand.",
        "baseline_growth": {c: baseline_growth(c) for c in ("zk0.1", "zk0")},
        "nics": nics(2028),
    }
    DEST.write_text(json.dumps(out, indent=1) + "\n")
    print(f"wrote {DEST.relative_to(ROOT)}: baseline growth 2027-30 "
          f"{out['baseline_growth']['zk0.1']['mean_pct']:.3f}% (zk0.1); employer NICs "
          f"{out['nics']['employer_avg_of_labour_cost']:.3f} of labour cost")


if __name__ == "__main__":
    main()
