"""Build the dashboard's data files from the committed model results.

    dashboard/src/data/aiScenarios.json   indices, labour share, growth, US endpoints
    dashboard/src/data/ukAiPaths.json     the 2000-2030 chart: OBR/ONS history + scenario paths

Inputs, all in ``data/``:

``scenarios.json``          model results (``python -m uk_growth_with_ai run``)
``og_uk_params.json``       trend parameters used to re-trend detrended output
``obr_history.json``        OBR/ONS outturn and March 2026 EFO forecast lines, with
                            per-panel provenance, and chart panel layout
``anthropic_us_2030.json``  Anthropic's published US 2030 endpoints
``scenarios_zk0.json``      the closed-capital bound (``zeta_K = 0``), shown beside
                            the central closure (``zeta_K = 0.1``, #16, #27)
``analysis/closure/output/zk0.5_*.json``  the #30 high-inflow solve (before R1-R4),
                            read for its 2030 wage gap only
``scenarios_fixed_spending.json``  optional: the same arms with government
                            spending and transfers held at baseline levels
                            (``run --baseline-spending``), the OBR convention
``scenarios_fixed_spending_zk0.json``  optional: the same at the closed-capital
                            bound

``python -m uk_growth_with_ai dashboard`` writes both files; ``--check`` fails if
the committed files differ from what the results produce.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from .arms import SHOCKED_ARMS
from .data_access import DATA, load_results, load_trend_params, normalise_arms
from .report import growth_path, labour_share, trend

DASHBOARD_DATA = Path(__file__).resolve().parent.parent / "dashboard" / "src" / "data"

YEARS = [2026, 2027, 2028, 2029, 2030]
ARMS = ["baseline", *SHOCKED_ARMS]
VARS = [["C", "Consumption"], ["I", "Investment"], ["G", "Government"],
        ["total_tax_revenue", "Tax revenue"], ["D", "Debt"], ["Y", "GDP"],
        ["w", "Wage rate (per efficiency unit)"], ["K", "Capital stock"], ["L", "Labour"]]

# The 2000-2030 chart shows the scenario paths over every model year.
PATH_YEARS = YEARS
# Display names must match ARM_META in dashboard/src/tabs/ai/series.js.  The
# baseline is OG-UK's own path on the OBR's central productivity assumption; the
# chart also carries the OBR's forecast line, so the name says whose line it is.
ARM_TRACE = {
    "baseline": ("OG-UK baseline", "#5a6470"),
    "share_shift_ramp": ("Automation only", "#2f6fb5"),
    "share_shift_tfp_ramp": ("Automation + productivity", "#1d7a4c"),
}

DERIVATION = (
    "Indexed to the 2026 baseline = 100: detrended OG-UK levels re-trended as "
    "OG-Core detrends them (e^{g_y t} for productivity, N_t for population; the "
    "wage carries productivity only, labour population only), using the g_y and "
    "g_n the run recorded, then divided by the baseline 2026 level. Generated by "
    "uk_growth_with_ai.dashboard_data from data/scenarios.json."
)


def _read(name: str) -> dict:
    return json.loads((DATA / name).read_text())


# The closed-capital bound and the #30 high-inflow solve (zeta_K = 0.5).
BOUND_RESULTS = DATA / "scenarios_zk0.json"
HIGH_INFLOW_DIR = Path(__file__).resolve().parent.parent / "analysis" / "closure" / "output"
SHOCKED = [a for a in ARMS if a != "baseline"]


def closure_gaps(res: dict) -> dict:
    """Gaps against the closure's own baseline over every exported year (2026-2035).

    GDP, GNI and wage gaps in %; debt/GDP gap in pp; the rise in r in basis
    points; the foreign-owned share of the extra capital (None where the
    capital gap is zero).  Also the baseline's income paid abroad and its
    debt/GDP, both in % of GDP.
    """
    b = res["baseline"]["series"]
    years = res["baseline"]["years"]
    n = len(years)

    def arm_block(arm):
        s = res[arm]["series"]
        gap = lambda v: [(s[v][i] / b[v][i] - 1) * 100 for i in range(n)]
        dk = [s["K"][i] - b["K"][i] for i in range(n)]
        return {
            "Y": gap("Y"), "GNI": gap("GNI"), "w": gap("w"),
            "debt_gdp_pp": [(s["D"][i] / s["Y"][i] - b["D"][i] / b["Y"][i]) * 100
                            for i in range(n)],
            "r_bp": [(s["r"][i] - b["r"][i]) * 1e4 for i in range(n)],
            "foreign_share_K": [None if abs(dk[i]) < 1e-12 else
                                (s["K_f"][i] - b["K_f"][i]) / dk[i] * 100 for i in range(n)],
        }

    return {
        "zeta_K": res["assumptions"]["closure"]["zeta_K"],
        "years": years,
        "baseline": {
            "abroad_pct_gdp": [(1 - b["GNI"][i] / b["Y"][i]) * 100 for i in range(n)],
            "debt_gdp": [b["D"][i] / b["Y"][i] * 100 for i in range(n)],
            # log change in the detrended K/L since 2026, x100: the baseline's
            # drift away from the inputs the Z targets are set at (#21)
            "kl_log_change": [float(np.log(b["K"][i] / b["L"][i] / (b["K"][0] / b["L"][0])) * 100)
                              for i in range(n)],
        },
        "arms": {a: arm_block(a) for a in SHOCKED},
    }


def high_inflow_wage() -> dict:
    """2030 wage gap of share_shift_tfp at zeta_K = 0.5, from the #30 solves."""
    arm = json.loads((HIGH_INFLOW_DIR / "zk0.5_share_shift_tfp_ramp.json").read_text())
    base = json.loads((HIGH_INFLOW_DIR / "zk0.5_baseline.json").read_text())
    i = arm["years"].index(2030)
    return {
        "zeta_K": arm["zeta_K"],
        "w_gap_2030": (arm["series"]["w"][i] / base["series"]["w"][i] - 1) * 100,
        "source": "#30 closure-sensitivity solve, before the R1-R4 reruns "
                  "(stock demographics, no debt calibration)",
    }


def closures(results=None) -> dict:
    """The central closure, the closed-capital bound, and the OBR's debt path."""
    res = results if results is not None else load_results()
    obr = next(p["obr"] for p in _read("obr_history.json")["panels"] if p["var"] == "D")
    obr_d = dict(zip(obr["x"], obr["y"]))
    return {
        "central": closure_gaps(res),
        "bound": closure_gaps(load_results(BOUND_RESULTS)),
        "high_inflow": high_inflow_wage(),
        "obr_debt_gdp": [obr_d[y] for y in YEARS],
    }


def ai_scenarios(results=None, oguk_dir=None) -> dict:
    res = results if results is not None else load_results()
    g_n, g_y = load_trend_params(oguk_dir, res)
    idx = {
        arm: {v: list(np.array(res[arm][v][:5]) * trend(v, g_y, g_n)
                      / res["baseline"][v][0] * 100)
              for v, _ in VARS}
        for arm in ARMS
    }
    return {
        "years": YEARS,
        "arms": ARMS,
        "vars": VARS,
        "idx": idx,
        "sl": {arm: list(labour_share(res[arm])) for arm in ARMS},
        "grow": {arm: list(growth_path(res[arm]["Y"], g_y, g_n)) for arm in ARMS},
        "anth": _read("anthropic_us_2030.json")["scenarios"],
        "assum": res["assumptions"],
        "derivation": DERIVATION,
        "model_ratios": model_ratios(res),
        "closures": closures(res),
        **({"fixed_spending": fs} if (fs := fixed_spending(res)) else {}),
    }


MODEL_RATIO_NOTE = (
    "OG-UK's own 2026 baseline ratios to GDP (%, model units). They differ from "
    "the OBR/ONS data; the UK paths chart applies the model's proportional "
    "changes in each ratio to the OBR's 2026 level rather than these levels."
)


def model_ratios(results=None) -> dict:
    """The model's 2026 baseline C/Y, I/Y, G/Y, tax/Y and D/Y, in %."""
    res = results if results is not None else load_results()
    b = res["baseline"]
    return {
        "year": YEARS[0],
        "ratios": {v: b[v][0] / b["Y"][0] * 100
                   for v in ["C", "I", "G", "total_tax_revenue", "D"]},
        "note": MODEL_RATIO_NOTE,
    }


FIXED_SPENDING = {"central": ("scenarios_fixed_spending.json", None),
                  "bound": ("scenarios_fixed_spending_zk0.json", BOUND_RESULTS)}


def fixed_spending(results=None) -> dict | None:
    """Gaps against the baseline with G and TR held at the baseline's levels.

    One block per closure, in the shape of ``closures()``: GDP, GNI and wage
    gaps in %, the debt/GDP gap in pp, over every exported year (2026-2035).
    The common-G/Y figures are not repeated here; they are in ``closures``.
    None if the central run is absent; the bound is included when its file is.
    """
    if not (DATA / FIXED_SPENDING["central"][0]).exists():
        return None
    out = {}
    for name, (fname, main_path) in FIXED_SPENDING.items():
        path = DATA / fname
        if not path.exists():
            continue
        fs = normalise_arms(json.loads(path.read_text()))
        main = (results if results is not None else load_results()) if main_path is None \
            else load_results(main_path)
        # The two files must share one baseline, or the comparison mixes runs
        # (the pre-R1-R4 fixed-spending file against the R1-R4 main run, #27).
        if not np.allclose(fs["baseline"]["Y"], main["baseline"]["Y"], rtol=1e-12, atol=0):
            raise ValueError(f"data/{fname} has a different baseline "
                             "from the main results; re-run or remove it")
        g = closure_gaps(fs)
        base_g = fs["baseline"]["series"]["G"]
        base_tr = fs["baseline"]["series"]["TR"]
        for a in SHOCKED:
            s = fs[a]["series"]
            if s["G"] != base_g or s["TR"] != base_tr:
                raise ValueError(f"data/{fname}: {a} does not hold G and TR at the "
                                 "baseline's levels")
        out[name] = {
            "zeta_K": g["zeta_K"],
            "years": g["years"],
            "note": fs["assumptions"].get("fiscal", ""),
            "Z_share_shift": fs["assumptions"]["Z_share_shift"],
            "arms": {a: {v: g["arms"][a][v] for v in ("Y", "GNI", "w", "debt_gdp_pp")}
                     for a in SHOCKED},
        }
    return out


def uk_paths(results=None, ai=None) -> dict:
    """Scenario paths rebased to the OBR/ONS line at 2026.

    GDP: OBR 2026 level times the scenario's GDP index / 100. Ratios: OBR 2026
    value times the scenario's model ratio over the baseline's 2026 model ratio,
    so the paths start at the OBR's level and move at the model's rate. The
    fiscal panels are fiscal years labelled by start year, so 2026 is 2026-27.
    """
    res = results if results is not None else load_results()
    ai = ai if ai is not None else ai_scenarios(res)
    panels = []
    n = len(PATH_YEARS)
    for p in _read("obr_history.json")["panels"]:
        v, obr = p["var"], p["obr"]
        o26 = dict(zip(obr["x"], obr["y"]))[2026]
        traces = [obr]
        for arm in ARMS:
            if v == "Y":
                y = [o26 * x / 100 for x in ai["idx"][arm]["Y"][:n]]
            else:
                b0 = res["baseline"][v][0] / res["baseline"]["Y"][0]
                y = [o26 * (res[arm][v][i] / res[arm]["Y"][i]) / b0 for i in range(n)]
            name, color = ARM_TRACE[arm]
            traces.append({
                "name": name, "x": PATH_YEARS, "y": [round(x, 3) for x in y],
                "color": color, "width": 2.4, "dash": "solid",
                "hovertemplate": f"%{{x}}: %{{y:.2f}}<extra>{name}</extra>",
                "legendgroup": name, "showlegend": True,
            })
        panels.append({"title": p["title"], "traces": traces, "shapes": p["shapes"],
                       "yRangeMode": p["yRangeMode"], "provenance": p["provenance"]})
    return {"panels": panels}


def _dump(obj) -> str:
    return json.dumps(obj, indent=1)


def build(results=None, oguk_dir=None) -> dict[str, str]:
    """File name -> JSON text, exactly as committed."""
    res = results if results is not None else load_results()
    ai = ai_scenarios(res, oguk_dir)
    return {"aiScenarios.json": _dump(ai), "ukAiPaths.json": _dump(uk_paths(res, ai))}


def write(out_dir=DASHBOARD_DATA, results=None, oguk_dir=None) -> list[Path]:
    out = Path(out_dir)
    paths = []
    for name, text in build(results, oguk_dir).items():
        (out / name).write_text(text)
        paths.append(out / name)
    return paths


def stale(out_dir=DASHBOARD_DATA, results=None, oguk_dir=None) -> list[str]:
    """Names of dashboard files that differ from what the results produce."""
    out = Path(out_dir)
    return [name for name, text in build(results, oguk_dir).items()
            if not (out / name).exists() or (out / name).read_text() != text]
